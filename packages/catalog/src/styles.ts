const STYLE_BY_ID = new Map(STYLE_PRESETS.map((style) => [style.id, style]));

export function getStylePreset(id: string): StylePreset | undefined {
  return STYLE_BY_ID.get(id);
}

/** Material id a style prefers for a scope (undefined when unmapped). */
export function styleMaterialFor(styleId: string, scope: keyof StylePreset['materials']): string | undefined {
  return STYLE_BY_ID.get(styleId)?.materials[scope];
}

/** True when a style tags a catalogue item (used for "AI 推荐" badges). */
export function skuMatchesStyle(styleTags: string[], styleId: string): boolean {
  return styleTags.includes(styleId);
}
