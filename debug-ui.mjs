import { chromium } from '@playwright/test';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, locale: 'zh-CN' });
page.on('console', m => console.log('[console]', m.type(), m.text().slice(0,200)));
page.on('pageerror', e => console.log('[pageerror]', e.message));
await page.goto('http://localhost:5173/', { waitUntil: 'domcontentloaded' });
const btns = await page.getByRole('button', { name: '导入图纸' }).count();
console.log('import buttons', btns);
await page.getByRole('button', { name: '导入图纸' }).first().click();
await page.waitForURL(/\/project\//, { timeout: 20000 });
await page.waitForTimeout(1000);
console.log('inputs', await page.locator('input[type=file]').count());
const visible = await page.locator('body').innerText();
console.log('text has 识别第:', /识别第 \d+ 页/.test(visible), '| 上传 active');
await page.locator('input[type=file]').first().setInputFiles('/Users/cillivian/Downloads/123.pdf');
await page.waitForTimeout(8000);
const text = await page.locator('body').innerText();
console.log('after upload text snippet:', text.slice(0, 600).replace(/\n{2,}/g, ' | '));
await page.screenshot({ path: '/tmp/ui-debug-pdf.png', fullPage: true });
await browser.close();
