import { chromium } from '@playwright/test';
const browser = await chromium.launch({ headless: true, channel: 'chromium', args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, deviceScaleFactor: 1 });
page.on('pageerror', (error) => console.log('pageerror', error.message));
const response = await page.goto(process.argv[2] ?? 'http://localhost:5173', { waitUntil: 'networkidle' });
console.log('status', response?.status(), 'title', await page.title());
await page.waitForTimeout(1200);
await page.screenshot({ path: process.argv[3] ?? '/tmp/hd-gallery.png', timeout: 20000 });
console.log('screenshot ok');
await browser.close();
